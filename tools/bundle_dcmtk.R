# tools/bundle_dcmtk.R
# Synchronizes DCMTK 3.7.1 data dictionary, C++ builtin dictionary table,
# and trimmed C++ module sources/headers from upstream DCMTK clone.

args <- commandArgs(trailingOnly = TRUE)
upstream_dir <- if (length(args) >= 1) args[1] else "../dcmtk_upstream"
pkg_dir <- normalizePath(".", mustWork = TRUE)

if (!dir.exists(upstream_dir)) {
  stop("Upstream DCMTK directory not found at: ", upstream_dir)
}

cat("=== Syncing DCMTK 3.7.1 Dictionary & Metadata ===\n")
dic_file <- file.path(upstream_dir, "dcmdata", "data", "dicom.dic")
if (!file.exists(dic_file)) {
  stop("Cannot find dicom.dic in upstream DCMTK: ", dic_file)
}

# Copy dicom.dic to inst/extdata/dicom.dic
dir.create(file.path(pkg_dir, "inst", "extdata"), recursive = TRUE, showWarnings = FALSE)
file.copy(dic_file, file.path(pkg_dir, "inst", "extdata", "dicom.dic"), overwrite = TRUE)

# Parse dicom.dic
lines <- readLines(dic_file, warn = FALSE, encoding = "UTF-8")
lines <- lines[!grepl("^\\s*#", lines) & nzchar(trimws(lines))]
parts <- strsplit(lines, "\t+")
parts <- parts[lengths(parts) >= 4]

dic_df <- data.frame(
  tag = toupper(vapply(parts, `[[`, character(1), 1)),
  vr = vapply(parts, `[[`, character(1), 2),
  keyword = vapply(parts, `[[`, character(1), 3),
  vm = vapply(parts, `[[`, character(1), 4),
  version = vapply(parts, function(x) if (length(x) >= 5) x[5] else "DICOM", character(1)),
  stringsAsFactors = FALSE
)

# Remove duplicate tags (later entries override earlier ones per DCMTK spec)
dic_df <- dic_df[!duplicated(dic_df$tag, fromLast = TRUE), ]

# Load existing dicom_tags.rda to preserve human-readable names where available
legacy_rda <- file.path(pkg_dir, "data", "dicom_tags.rda")
if (file.exists(legacy_rda)) {
  env <- new.env(parent = emptyenv())
  load(legacy_rda, envir = env)
  old_tags <- env$dicom_tags
  old_map <- stats::setNames(old_tags$name, toupper(old_tags$tag))
} else {
  old_map <- character(0)
}

# Convert CamelCase keyword to spaced human-readable name for new tags
camel_to_title <- function(x) {
  s <- gsub("([a-z0-9])([A-Z])", "\\1 \\2", x)
  s <- gsub("([A-Z]+)([A-Z][a-z])", "\\1 \\2", s)
  s
}

human_name <- unname(old_map[dic_df$tag])
missing_idx <- is.na(human_name) | !nzchar(human_name)
human_name[missing_idx] <- camel_to_title(dic_df$keyword[missing_idx])

retired_flag <- ifelse(grepl("RET", dic_df$version, ignore.case = TRUE), "RET", "")

dicom_tags <- data.frame(
  tag = dic_df$tag,
  name = human_name,
  keyword = dic_df$keyword,
  vr = dic_df$vr,
  vm = dic_df$vm,
  retired = retired_flag,
  stringsAsFactors = FALSE
)
rownames(dicom_tags) <- NULL

save(dicom_tags, file = file.path(pkg_dir, "data", "dicom_tags.rda"), compress = "xz")
cat("Updated data/dicom_tags.rda with", nrow(dicom_tags), "DICOM tags from DCMTK 3.7.1.\n")

# Generate C++ built-in dictionary header for exact, zero-overhead tag lookups
std_idx <- grepl("^\\([0-9A-F]{4},[0-9A-F]{4}\\)$", dicom_tags$tag)
std_tags <- dicom_tags[std_idx, ]

groups <- paste0("0x", substr(std_tags$tag, 2, 5))
elems  <- paste0("0x", substr(std_tags$tag, 7, 10))
esc_str <- function(s) gsub('"', '\\"', gsub("\\\\", "\\\\\\\\", s))

cpp_lines <- c(
  "// Auto-generated by tools/bundle_dcmtk.R from DCMTK 3.7.1 dicom.dic (PS 3.6-2026d)",
  "#ifndef DICOMTK_DICT_BUILTIN_H",
  "#define DICOMTK_DICT_BUILTIN_H",
  "",
  "#include <cstdint>",
  "#include <cstddef>",
  "",
  "namespace dicomtk {",
  "",
  "struct DcmDictEntry {",
  "  uint16_t group;",
  "  uint16_t element;",
  "  const char* vr;",
  "  const char* keyword;",
  "  const char* name;",
  "  const char* vm;",
  "};",
  "",
  "static const DcmDictEntry kBuiltinDict[] = {"
)

entry_lines <- sprintf(
  '  {%s, %s, "%s", "%s", "%s", "%s"}',
  groups,
  elems,
  esc_str(std_tags$vr),
  esc_str(std_tags$keyword),
  esc_str(std_tags$name),
  esc_str(std_tags$vm)
)
cpp_lines <- c(
  cpp_lines,
  paste0(entry_lines, collapse = ",\n"),
  "};",
  "",
  sprintf("static const std::size_t kBuiltinDictSize = %d;", nrow(std_tags)),
  "",
  "} // namespace dicomtk",
  "",
  "#endif // DICOMTK_DICT_BUILTIN_H"
)

writeLines(cpp_lines, file.path(pkg_dir, "src", "dcmtk_dict_builtin.h"), useBytes = TRUE)
cat("Generated src/dcmtk_dict_builtin.h with", nrow(std_tags), "standard tags.\n")

# Record DCMTK version metadata and upstream commit SHA
ver_file <- file.path(upstream_dir, "VERSION")
dcmtk_ver <- if (file.exists(ver_file)) trimws(readLines(ver_file, warn = FALSE)[1]) else "3.7.1"
upstream_sha <- tryCatch({
  out <- system2("git", c("-C", shQuote(upstream_dir), "rev-parse", "HEAD"), stdout = TRUE, stderr = FALSE)
  if (length(out) >= 1 && nzchar(trimws(out[1]))) trimws(out[1]) else "unknown"
}, error = function(e) "unknown")

meta_lines <- c(
  paste0("version=", dcmtk_ver),
  paste0("commit=", upstream_sha),
  paste0("tags=", nrow(dicom_tags)),
  paste0("standard_tags=", nrow(std_tags))
)
writeLines(meta_lines, file.path(pkg_dir, "inst", "extdata", "dcmtk_upstream_version.txt"), useBytes = TRUE)
cat("DCMTK upstream version:", dcmtk_ver, "(commit:", substr(upstream_sha, 1, 8), ")\n")

# Sync all 23 DCMTK module header directories into inst/include/dcmtk/
cat("Syncing DCMTK C++ module headers into inst/include/dcmtk/...\n")
inc_dst <- file.path(pkg_dir, "inst", "include", "dcmtk")
dir.create(inc_dst, recursive = TRUE, showWarnings = FALSE)
all_modules <- c(
  "ofstd", "oflog", "oficonv", "dcmdata", "dcmimgle", "dcmimage",
  "dcmjpeg", "dcmjpls", "dcmnet", "dcmsr", "dcmiod", "dcmfg",
  "dcmrt", "dcmseg", "dcmpmap", "dcmtract", "dcmect", "dcmpstat",
  "dcmqrdb", "dcmwlm", "dcmsign", "dcmtls", "cmr", "dcmloco"
)
for (m in all_modules) {
  src_inc <- file.path(upstream_dir, m, "include", "dcmtk")
  if (dir.exists(src_inc)) {
    sub_dirs <- list.files(src_inc, full.names = TRUE)
    for (sd in sub_dirs) {
      file.copy(sd, inc_dst, recursive = TRUE, overwrite = TRUE)
    }
  }
}
cfg_inc <- file.path(upstream_dir, "config", "include", "dcmtk", "config")
if (dir.exists(cfg_inc)) {
  dir.create(file.path(inc_dst, "config"), recursive = TRUE, showWarnings = FALSE)
  file.copy(list.files(cfg_inc, full.names = TRUE), file.path(inc_dst, "config"), recursive = TRUE, overwrite = TRUE)
}
cat("Synced DCMTK module headers into inst/include/dcmtk/.\n")

# If --bundle-sources flag is passed, copy trimmed C++ module headers and sources into src/dcmtk
if ("--bundle-sources" %in% args) {
  cat("Bundling trimmed DCMTK C++ headers and sources into src/dcmtk...\n")
  dst_root <- file.path(pkg_dir, "src", "dcmtk")
  dir.create(dst_root, recursive = TRUE, showWarnings = FALSE)
  file.copy(file.path(upstream_dir, "CMakeLists.txt"), file.path(dst_root, "CMakeLists.txt"), overwrite = TRUE)
  file.copy(file.path(upstream_dir, "VERSION"), file.path(dst_root, "VERSION"), overwrite = TRUE)
  
  # Copy CMake and config directories
  for (d in c("CMake", "config")) {
    src_d <- file.path(upstream_dir, d)
    if (dir.exists(src_d)) {
      dir.create(file.path(dst_root, d), recursive = TRUE, showWarnings = FALSE)
      file.copy(list.files(src_d, full.names = TRUE), file.path(dst_root, d), recursive = TRUE, overwrite = TRUE)
    }
  }
  
  for (m in all_modules) {
    src_m <- file.path(upstream_dir, m)
    if (!dir.exists(src_m)) next
    dst_m <- file.path(dst_root, m)
    dir.create(dst_m, recursive = TRUE, showWarnings = FALSE)
    if (file.exists(file.path(src_m, "CMakeLists.txt"))) {
      file.copy(file.path(src_m, "CMakeLists.txt"), file.path(dst_m, "CMakeLists.txt"), overwrite = TRUE)
    }
    for (sub in c("include", "libsrc", "libijg8", "libijg12", "libijg16", "libcharls")) {
      src_sub <- file.path(src_m, sub)
      if (dir.exists(src_sub)) {
        dir.create(file.path(dst_m, sub), recursive = TRUE, showWarnings = FALSE)
        file.copy(list.files(src_sub, full.names = TRUE), file.path(dst_m, sub), recursive = TRUE, overwrite = TRUE)
      }
    }
  }
  cat("Finished bundling trimmed DCMTK modules into src/dcmtk.\n")
}

